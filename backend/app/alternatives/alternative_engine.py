if __name__ == "__main__":

    from ..intent.intent_engine import (
        IntentEngine,
    )

    from ..intent.intent_contract import (
        IntentContractBuilder,
    )

    from ..parser.command_parser import (
        LinuxCommandParser,
    )

    from ..risk.risk_engine import (
        RiskEngine,
    )

    from ..alignment.alignment_engine import (
        IntentCommandAligner,
    )

    from ..policy.policy_engine import (
        PolicyEngine,
    )

    intent_engine = IntentEngine()

    contract_builder = (
        IntentContractBuilder()
    )

    parser = LinuxCommandParser()

    risk_engine = RiskEngine()

    aligner = IntentCommandAligner()

    policy_engine = PolicyEngine()

    alternative_engine = (
        AlternativeEngine()
    )

    test_cases = [

        (
            "I want to view files in ~/Downloads",
            "rm -rf ~/Downloads",
        ),

        (
            "I want to delete an old file in ~/Downloads",
            "rm ~/Downloads/old.txt",
        ),

        (
            "I want to view files in ~/Downloads",
            "sudo cat /etc/passwd",
        ),

        (
            "I want to view files",
            "unknown-command /tmp/test",
        ),

        (
            "I want to download a file",
            "curl https://example.com",
        ),

        (
            "I want to view files in ~/Downloads",
            "ls -la ~/Downloads",
        ),
    ]

    print("=" * 70)
    print(
        "SafeShell AI - Alternative Engine Test"
    )
    print("=" * 70)

    for goal, command in test_cases:

        intent = intent_engine.classify(
            goal
        )

        contract = contract_builder.build(
            goal,
            intent,
        )

        analysis = parser.parse(
            command
        )

        risk = risk_engine.assess(
            analysis
        )

        alignment = aligner.align(
            contract,
            analysis,
        )

        decision = policy_engine.decide(
            contract=contract,
            command=analysis,
            risk=risk,
            alignment=alignment,
        )

        alternative = alternative_engine.suggest(
            contract=contract,
            command=analysis,
            risk=risk,
            alignment=alignment,
            decision=decision,
        )

        print()
        print("USER:")
        print(goal)

        print()
        print("COMMAND:")
        print(command)

        print()
        print("DECISION:")
        print(decision.decision)

        print()
        print("ALTERNATIVE AVAILABLE:")
        print(alternative.available)

        print()
        print("TITLE:")
        print(alternative.title)

        print()
        print("SAFER COMMAND:")
        print(alternative.safer_command)

        print()
        print("EXPLANATION:")
        print(alternative.explanation)

        print()
        print("BENEFITS:")

        for benefit in alternative.benefits:

            print(
                " -",
                benefit,
            )

        print()
        print("WARNINGS:")

        for warning in alternative.warnings:

            print(
                " -",
                warning,
            )

        print("-" * 70)